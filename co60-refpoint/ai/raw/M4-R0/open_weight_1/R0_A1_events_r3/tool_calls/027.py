def mu_compton(E):
    a = E / m_e
    t1 = (1+a)/a**2 * (2*(1+a)/(1+2*a) - np.log(1+2*a)/a)
    t2 = np.log(1+2*a)/(2*a)
    t3 = (1+3*a)/(1+2*a)**2
    return 2*np.pi*r_e**2 * (t1 + t2 - t3) * e_per_cm3

